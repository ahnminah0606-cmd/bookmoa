export function getRandomBookQuestion(title: string, author?: string, excludeQuestion?: string): string {
  const cleanTitle = title || '이 책';
  const cleanAuthor = author || '저자';

  const formattedQuestions = BOOK_QUESTION_TEMPLATES.map(template =>
    template.replace(/{title}/g, cleanTitle).replace(/{author}/g, cleanAuthor)
  );

  const available = formattedQuestions.filter(q => q !== excludeQuestion);
  if (available.length === 0) return formattedQuestions[0];

  const randomIndex = Math.floor(Math.random() * available.length);
  return available[randomIndex];
}
